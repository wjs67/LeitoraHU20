package GLPI::Agent::Task::Inventory::Win32::USB;

use strict;
use warnings;

use parent 'GLPI::Agent::Task::Inventory::Module';

use GLPI::Agent::Tools;
use GLPI::Agent::Tools::Win32;
use GLPI::Agent::Tools::USB;

use constant    category    => "usb";

sub isEnabled {
    return 1;
}

sub doInventory {
    my (%params) = @_;

    my $inventory = $params{inventory};

    foreach my $device (_getDevices(logger => $params{logger}, datadir => $params{datadir})) {
        $inventory->addEntry(
            section => 'USBDEVICES',
            entry   => $device
        );
    }
}

sub _getDevices {
    my (%params) = @_;

    my @devices;
    my $seen;

    foreach my $device (_getDevicesFromWMI(%params)) {

        next if $device->skip();

        # Avoid duplicates
        my $dedupkey = join('-', $device->vendorid, $device->productid, $device->serial);
        next if $seen->{$dedupkey}++;

        # cleanup pseudo serial generated by windows
        $device->delete_serial() if $device->serial =~ /&/;

        # Update device
        $device->update_by_ids();
        $device->update();

        push @devices, $device->dump();
    }

    return @devices;
}

sub _getDevicesFromWMI {
    my (%params) = @_;

    my @devices;

    my ($vendorid, $productid, $serial);

    foreach my $object (getWMIObjects(
        class      => 'CIM_LogicalDevice',
        properties => [ qw/Caption DeviceID Name/ ]
    )) {
        next unless ($vendorid, $productid, $serial) = $object->{DeviceID} =~ /^USB\\VID_(\w+)&PID_(\w+)\\(.*)/;

        # Support manufacturers wrongly using iSerial with fields definition
        $serial = $1 if $serial =~ /^S\/N:([0-9A-F]+)/i;

        # SecuGen HU20 Biometric Reader (VID: 1162 / PID: 2200) serial injection
        # Inject physical serial from Windows registry before USB object instantiation
        if ($vendorid =~ /^1162$/i && $productid =~ /^2200$/i) {
            $serial = _getSecugenHU20Serial(%params);
            # Append " HU20" to device name for identification
            $object->{Name} .= " HU20" unless $object->{Name} =~ /HU20/i;
        }

        push @devices, GLPI::Agent::Tools::USB->new(
            logger      => $params{logger},
            caption     => $object->{Caption},
            name        => $object->{Name},
            vendorid    => $vendorid,
            productid   => $productid,
            serial      => $serial
        );
    }

    return @devices;
}

sub _getSecugenHU20Serial {
    my (%params) = @_;

    my $logger       = $params{logger};
    my $serial_found = '';

    # 1. Try native GLPI::Agent::Tools::Win32 routines
    if (defined &getRegistryValue) {
        $serial_found = getRegistryValue(
            path => "HKLM/SOFTWARE/CustomInventory/HU20/SerialNumber"
        );
    }

    if (!$serial_found && defined &getRegistryKey) {
        my $key = getRegistryKey(
            path   => "SOFTWARE/CustomInventory/HU20",
            logger => $logger
        );
        if ($key) {
            $serial_found = $key->{'/SerialNumber'} || $key->{'SerialNumber'};
        }
    }

    # 2. Try Win32::TieRegistry (resilient eval wrapper)
    if (!$serial_found) {
        eval {
            require Win32::TieRegistry;
            Win32::TieRegistry->import( Delimiter => '/', ArrayValues => 0 );
            
            my @paths = (
                'HKEY_LOCAL_MACHINE/SOFTWARE/CustomInventory/HU20/',
                'HKEY_LOCAL_MACHINE/SOFTWARE/WOW6432Node/CustomInventory/HU20/'
            );

            foreach my $path (@paths) {
                my $reg_key = $Win32::TieRegistry::Registry->{$path};
                if (defined $reg_key && defined $reg_key->{'/SerialNumber'}) {
                    $serial_found = $reg_key->{'/SerialNumber'};
                    last;
                }
            }
        };
    }

    # 3. Fallback to native Windows reg.exe utility
    if (!$serial_found) {
        my $reg_output = `reg query "HKLM\\SOFTWARE\\CustomInventory\\HU20" /v SerialNumber 2>&1`;
        if ($reg_output !~ /REG_/i) {
            $reg_output = `reg query "HKLM\\SOFTWARE\\WOW6432Node\\CustomInventory\\HU20" /v SerialNumber 2>&1`;
        }
        if ($reg_output =~ /SerialNumber\s+REG_\w+\s+([A-Za-z0-9]+)/i) {
            $serial_found = $1;
        }
    }

    # 4. Strict regex validation and return
    if (defined $serial_found && $serial_found ne '' && $serial_found =~ /^[A-Za-z0-9]{5,}$/) {
        return $serial_found;
    }

    # Return fallback value (indicates device present but serial unreadable)
    return 'H99999999999';
}

1;
